// Write a Java programme to add two integers entered by the user using Scanner class
import java.util.*;
public class Day2_exp2{
  public static void main(String[] args){
    Scanner scan = new Scanner(System.in);
    int a = scan.nextInt();
    int b = scan.nextInt();
    int c = a + b;
    System.out.println(c);
  }
}  